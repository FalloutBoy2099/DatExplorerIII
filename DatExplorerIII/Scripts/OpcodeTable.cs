	/// <summary>
	/// How each opcode is written in the source: its name, the number of arguments it takes and what kind of opcode it is. The table
	/// is the one of Fallout 2 with the opcodes sfall adds, and the few Fallout 1 differs by.
	/// </summary>
	internal static class OpcodeTable
	{
		private static readonly Dictionary<Opcode, OpcodeAttributes> Fallout2Attributes = CreateFallout2Attributes();
		private static readonly Dictionary<Opcode, OpcodeAttributes> Fallout1Attributes = CreateFallout1Attributes();

		/// <summary>The names of the functions a script can call, as the source writes them (no operators, no placeholders).</summary>
		public static IReadOnlySet<String> FunctionNames { get; } = CreateFunctionNames();

		public static OpcodeAttributes GetAttributes(Opcode opcode, ScriptGame game)
		{
			OpcodeAttributes? attributes;
			if (game == ScriptGame.Fallout1 && Fallout1Attributes.TryGetValue(opcode, out attributes))
				return attributes;
			if (!Fallout2Attributes.TryGetValue(opcode, out attributes))
				throw new ScriptFormatException($"Error: Attempt to obtain attributes of unknown opcode 0x{(UInt16)opcode:X4}");
			return attributes;
		}

		private static HashSet<String> CreateFunctionNames()
		{
			HashSet<String> names = [with(StringComparer.OrdinalIgnoreCase)];
			foreach (OpcodeAttributes attributes in Fallout2Attributes.Values.Concat(Fallout1Attributes.Values))
			{
				String name = attributes.Name;
				if (name.Length > 0 && (Char.IsAsciiLetter(name[0]) || name[0] == '_') && name.All(character => Char.IsAsciiLetterOrDigit(character) || character == '_'))
					names.Add(name);
			}

			return names;
		}

